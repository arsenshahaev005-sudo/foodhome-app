// Mechanical SVG-to-VectorDrawable conversion: reuse the approved PWA artwork.
// No image synthesis, network access or sibling repository needed in CI.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const svg = readFileSync(path.join(root, 'assets/branding/pwa-logo.svg'), 'utf8');
assert.match(svg, /viewBox="850 1850 2850 500"/);
assert.match(svg, /transform="translate\(0\.000000,4028\.000000\) scale\(0\.100000,-0\.100000\)"/);
assert(!/<(?:image|text|use|clipPath|filter)\b/.test(svg), 'Unsupported SVG feature');
const paths = [...svg.matchAll(/<path\s+fill="(#[a-fA-F0-9]{6})"\s+d="([^"]+)"\s*\/>/g)];
assert(paths.length > 0 && paths.length === (svg.match(/<path\b/g) ?? []).length);
const body = paths.map(([, fill, d]) => `        <path android:fillColor="${fill}" android:pathData="${d.replace(/\s+/g, ' ').trim()}" />`).join('\n');
const logo = `    <group android:translateX="-850" android:translateY="-1850">\n      <group android:translateY="4028" android:scaleX="0.1" android:scaleY="-0.1">\n${body}\n      </group>\n    </group>`;
const vector = (splash) => `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-android-branding.mjs from the PWA logo. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="${splash ? 288 : 280}dp" android:height="${splash ? 288 : 49.122807}dp"\n    android:viewportWidth="2850" android:viewportHeight="${splash ? 2850 : 500}">\n${splash ? '  <group android:translateX="513" android:translateY="1265" android:scaleX="0.64" android:scaleY="0.64">\n' : ''}${logo}\n${splash ? '  </group>\n' : ''}</vector>\n`;
for (const [name, splash] of [['foodhome_wordmark', false], ['foodhome_splash_wordmark', true]]) {
  const target = path.join(root, `android/app/src/main/res/drawable/${name}.xml`);
  const expected = vector(splash);
  if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), expected);
  else { mkdirSync(path.dirname(target), { recursive: true }); writeFileSync(target, expected); }
}
console.log(`PWA logo: ${paths.length} original paths; Android vectors ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
